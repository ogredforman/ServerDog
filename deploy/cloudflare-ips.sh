#!/bin/sh
# Run on the droplet as root. Fetches Cloudflare's published IP ranges, then:
#   - allows ports 80 and 443 in ufw from those ranges only;
#   - writes /etc/apache2/conf-available/cloudflare-remoteip.conf so Apache logs the
#     visitor's address (CF-Connecting-IP) and trusts that header only from Cloudflare.
# Safe to re-run when Cloudflare changes its ranges (rare): existing rules are kept, new
# ranges are added. It never touches SSH rules. See CLOUDFLARE.md step 7.
set -eu

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

curl -fsS https://www.cloudflare.com/ips-v4 -o "$tmp/v4"
curl -fsS https://www.cloudflare.com/ips-v6 -o "$tmp/v6"
# The files may lack a trailing newline; keep the last v4 and first v6 range apart.
{ cat "$tmp/v4"; echo; cat "$tmp/v6"; echo; } | grep -E '^[0-9a-fA-F:.]+/[0-9]+$' > "$tmp/all"
[ -s "$tmp/all" ] || { echo "no ranges fetched" >&2; exit 1; }

while read -r range; do
	ufw allow proto tcp from "$range" to any port 80,443 comment 'Cloudflare' >/dev/null
done < "$tmp/all"

conf=/etc/apache2/conf-available/cloudflare-remoteip.conf
{
	echo "# Generated by cloudflare-ips.sh on $(date -u +%Y-%m-%d). Re-run to refresh."
	echo "RemoteIPHeader CF-Connecting-IP"
	sed 's/^/RemoteIPTrustedProxy /' "$tmp/all"
} > "$conf"

echo "ufw: allowed 80,443 from $(wc -l < "$tmp/all") Cloudflare ranges"
echo "wrote $conf (enable: a2enconf cloudflare-remoteip && systemctl reload apache2)"
